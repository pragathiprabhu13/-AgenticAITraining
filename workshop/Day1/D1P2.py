# Day1\D1P2.py
"""
FinDesk V2 - Graph-Based Finance Assistant using LangGraph
Day 1 / Session 2 - runnable checkpoint (D1P2.py)

WHAT THIS VERSION DOES
----------------------
Converts the Session 1 assistant into a LangGraph workflow:

             START
               |
               v
        Input Processing   (node 1 - cleans/normalises the question)
               |
               v
          LLM Response     (node 2 - runs the same LCEL chain as V1)
               |
               v
        Output Processing  (node 3 - formats the final reply)
               |
               v
              END

Key LangGraph concepts introduced here:
  * State        - a TypedDict that is the single source of truth
  * Nodes        - plain Python functions: state in -> partial update out
  * Edges        - START/END plus node-to-node wiring
  * compile()    - turns the builder into a runnable app
  * invoke()     - runs the whole graph once per question
  * stream()     - (optional, /steps) shows each node update as it happens

RUN
---
    python D1P2.py

COMMANDS INSIDE THE CHAT LOOP
------------------------------
    /steps      answer a question but print every node update (trace)
    /graph      print the graph structure
    /model      show active provider/model configuration
    /provider   switch provider (ollama / gemini)
    /exit       quit
"""

# Allows modern Python type annotations to be evaluated lazily.
from __future__ import annotations

# Imports Python's system module.
# It is used here to display errors and terminate the application.
import sys

# TypedDict allows us to define the expected structure of a dictionary.
# We use it to define the state that will be shared between graph nodes.
from typing import TypedDict

# StrOutputParser converts the language model's response into plain text.
from langchain_core.output_parsers import StrOutputParser

# Import important LangGraph components.
# START       - represents the beginning of the graph.
# END         - represents the completion of the graph.
# StateGraph  - helps us create a graph that operates using shared state.
from langgraph.graph import END, START, StateGraph

# Import the shared application modules.
# config        - manages provider configuration and environment settings.
# model_factory - creates the selected LLM (Gemini or Ollama).
# prompts       - contains reusable finance-related prompt instructions.
from common import config, model_factory, prompts


# ==========================================================================
# 1. STATE - the schema of the data that flows through the graph
# ==========================================================================

# Define the structure of the information shared between graph nodes.
# FinanceState is a TypedDict, meaning it describes a dictionary
# with predefined keys and their expected data types.
class FinanceState(TypedDict):

    # This documentation explains the purpose of the state.
    """Attributes shared by every node in the V2 workflow.

    TypedDict (from typing) gives LangGraph a static description of the
    state. Nodes receive the current state and return a DICTIONARY containing
    ONLY the keys they want to change - LangGraph merges it into the state.

    Fields
    ------
    question         : raw text typed by the employee
    cleaned_question : normalised text produced by input_processing
    answer           : raw model reply from llm_response
    final_output     : formatted reply produced by output_processing
    """

    # Stores the original question entered by the user.
    question: str

    # Stores the cleaned version of the original question.
    cleaned_question: str

    # Stores the response generated by the language model.
    answer: str

    # Stores the final formatted response displayed to the user.
    final_output: str


# ==========================================================================
# 2. GRAPH FACTORY - nodes are built inside a function so they can close
#    over the LLM chain chosen by the provider menu.
# ==========================================================================

# This function creates and compiles the complete LangGraph application.
# provider specifies which model provider should be used.
# None means that the provider configured in the .env file will be used.
def build_app(provider: str | None = None):

    """Compile and return the FinDesk V2 LangGraph application.

    Parameters
    ----------
    provider : str, optional
        "ollama" / "gemini"; None = value from .env.

    Returns
    -------
    Compiled graph (StateGraph.compile()) - supports .invoke()/.stream().
    """

    # Create the selected language model using the model factory.
    # The factory decides whether to create a Gemini or Ollama model.
    llm = model_factory.get_llm(provider)

    # Create the LangChain processing pipeline.
    # Step 1: Finance prompt prepares the system instructions and question.
    # Step 2: LLM generates the response.
    # Step 3: StrOutputParser converts the response into plain text.
    #
    # The pipe operator connects these components into one LCEL chain.
    chain = prompts.finance_prompt(prompts.GENERAL_FINANCE_SYSTEM) | llm | StrOutputParser()


    # ------------------------------------------------------------------
    # NODE 1: input processing
    # A node is a function  (state) -> dict-of-updates.
    # Returning {"cleaned_question": ...} tells LangGraph to overwrite only
    # that key; every other key keeps its previous value.
    # ------------------------------------------------------------------

    # Define the first graph node.
    # It receives the current FinanceState and returns a dictionary
    # containing the information that needs to be updated.
    def input_processing(state: FinanceState) -> dict:

        # Remove unnecessary spaces from the question.
        # split() separates the text wherever whitespace occurs.
        # " ".join() joins the words using exactly one space.
        #
        # Example:
        # "  What   is    finance?  "
        # becomes:
        # "What is finance?"
        question = " ".join(state["question"].split())

        # Check whether the cleaned question is empty.
        if not question:

            # If the question is empty, assign a default message.
            question = "(empty question)"

        # The original question remains unchanged in the state.
        # Only cleaned_question is updated here.
        # This makes it possible to retain the original input for reference.
        #
        # Return a dictionary containing the updated value.
        return {"cleaned_question": question}


    # ------------------------------------------------------------------
    # NODE 2: LLM response
    # Reads the cleaned question, runs the chain built above and stores the
    # model's text in state["answer"]. `chain` is captured from the enclosing
    # build_app() scope (a closure) - this is the standard pattern when the
    # model depends on runtime configuration.
    # ------------------------------------------------------------------

    # Define the second graph node.
    # This node takes the cleaned question and sends it to the LLM chain.
    def llm_response(state: FinanceState) -> dict:

        # Execute the LCEL chain using the cleaned question.
        # The dictionary key "question" matches the placeholder
        # used inside the finance prompt template.
        #
        # invoke() sends the input through:
        # Prompt -> LLM -> Output Parser.
        #
        # The result is stored in the answer variable.
        answer = chain.invoke({"question": state["cleaned_question"]})

        # Return the model response as an update to the graph state.
        return {"answer": answer}


    # ------------------------------------------------------------------
    # NODE 3: output processing
    # Presentation only - no model call. It formats the answer so the CLI
    # can print state["final_output"] directly.
    # ------------------------------------------------------------------

    # Define the third graph node.
    # Its responsibility is to prepare the model response for display.
    def output_processing(state: FinanceState) -> dict:

        # Get the answer from the graph state.
        # get() returns an empty string if the answer key is unavailable.
        # strip() removes unnecessary spaces at the beginning and end.
        answer = state.get("answer", "").strip()

        # Add the FinDesk label before the model's answer.
        # This is an example of Python f-string formatting.
        final = f"FinDesk: {answer}"

        # Return the formatted response as an update to the graph state.
        return {"final_output": final}


    # ------------------------------------------------------------------
    # 3. WIRE THE GRAPH
    # StateGraph(FinanceState) declares the state schema; add_node()
    # registers functions; add_edge() draws the arrows. START and END are
    # special nodes marking entry and exit.
    # ------------------------------------------------------------------

    # Create a graph builder using FinanceState as its state definition.
    builder = StateGraph(FinanceState)

    # Register the first node with the graph.
    # The node name is input_processing and the function is input_processing.
    builder.add_node("input_processing", input_processing)

    # Register the second node responsible for generating the LLM response.
    builder.add_node("llm_response", llm_response)

    # Register the third node responsible for formatting the final response.
    builder.add_node("output_processing", output_processing)

    # Connect the START point to the first node.
    # This tells LangGraph where execution should begin.
    builder.add_edge(START, "input_processing")

    # Connect the first node to the second node.
    # After cleaning the question, execution moves to the LLM.
    builder.add_edge("input_processing", "llm_response")

    # Connect the second node to the third node.
    # After generating the answer, execution moves to output processing.
    builder.add_edge("llm_response", "output_processing")

    # Connect the third node to END.
    # This marks the completion of the graph workflow.
    builder.add_edge("output_processing", END)

    # compile() converts the graph builder into an executable application.
    # The returned application supports methods such as invoke() and stream().
    return builder.compile()


# ==========================================================================
# 4. GRAPH VISUALISATION
# ==========================================================================

# Define a function to display the structure of the compiled graph.
# app represents the compiled LangGraph application.
def print_graph(app) -> None:

    # Documentation describing the purpose of this function.
    """Print the graph structure (ASCII art when available)."""

    # get_graph() retrieves the graph structure from the compiled application.
    graph = app.get_graph()

    # Try to display the graph using an ASCII diagram.
    try:

        # draw_ascii() generates a text-based diagram of the graph.
        # The optional grandalf package is needed for this operation.
        print(graph.draw_ascii())

    # If ASCII drawing fails for any reason, execute this block.
    except Exception:

        # Display the names of all registered graph nodes.
        # n represents each node in the graph.
        print("Nodes :", [n for n in graph.nodes])

        # Display all connections between graph nodes.
        # e.source represents the starting node of an edge.
        # e.target represents the destination node of an edge.
        print("Edges :", [(e.source, e.target) for e in graph.edges])


