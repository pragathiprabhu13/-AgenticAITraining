# 5. INTERACTIVE CLI (same UX as V1, but every answer goes through the graph)
# ==========================================================================

# Store the welcome banner and available commands in a multiline string.
BANNER = """
------------------------------------------------------------
FinDesk V2 - Graph-Based Finance Assistant
Type a finance question, or one of:
  /steps      - answer a question showing each node update
  /graph      - print the graph structure
  /model      - show active model configuration
  /provider   - switch provider (ollama | gemini)
  /exit       - quit
------------------------------------------------------------"""


# Define a function to display the model selection menu.
# It returns the selected provider or None for the .env default.
def choose_provider() -> str | None:

    # Display a separator line.
    print("=" * 60)

    # Display the application name.
    print("FinDesk V2 - Graph-Based Finance Assistant")

    # Display another separator line.
    print("=" * 60)

    # Show the current provider and model configuration.
    print(f"Active configuration: {config.describe()}")

    # Display the available provider options.
    print("\nSelect model:")

    # Option 1: Select Gemini, which uses Google's cloud service.
    print("  1. Gemini   (cloud, requires GOOGLE_API_KEY in .env)")

    # Option 2: Select Ollama, which runs models locally.
    print("  2. Ollama   (local, default)")

    # Option 3: Use the provider configured in the .env file.
    print(f"  3. Use .env default (currently: {config.LLM_PROVIDER})")

    # Read the user's choice.
    # strip() removes spaces before and after the entered value.
    choice = input("Choice [3]: ").strip()

    # If the user enters 1, return Gemini as the selected provider.
    if choice == "1":
        return "gemini"

    # If the user enters 2, return Ollama as the selected provider.
    if choice == "2":
        return "ollama"

    # For option 3, an empty input or any other input,
    # return None so the .env default is used.
    return None


# Define a function to execute the graph while displaying
# the updates produced by individual nodes.
def run_with_trace(app, question: str) -> None:

    """Invoke the graph with stream_mode="updates".

    Instead of returning only the final state, .stream() yields one dict per
    executed node:  {"node_name": {keys it updated}}. Printing these shows
    students the execution order and exactly what each node contributed.
    """

    # Display the original question entered by the user.
    print(f"  question: {question}")

    # Create an initial state dictionary containing the user's question.
    # At this point, only the question is available.
    state: dict = {"question": question}

    # Execute the graph using stream().
    # stream_mode="updates" tells LangGraph to yield the updates
    # produced by each node rather than only the final state.
    #
    # Each iteration receives the updates from a graph execution step.
    for step in app.stream(state, stream_mode="updates"):

        # A step contains the node name and the dictionary of values
        # that the node updated.
        for node_name, update in step.items():

            # Display which node executed and what information it updated.
            print(f"  -> node '{node_name}' updated: {update}")

            # Merge the node's returned values into our local state dictionary.
            # update() adds new keys or replaces existing keys with new values.
            #
            # This locally reconstructs the final state from the streamed
            # partial updates.
            state.update(update)

    # Display the final formatted response.
    # get() returns "(no output)" if final_output is not available.
    print(f"  {state.get('final_output', '(no output)')}\n")


# Define the main function that controls the entire application.
def main() -> None:

    # Handle errors that may occur while initializing the application.
    try:

        # Display the provider selection menu and get the user's choice.
        provider = choose_provider()

        # Build and compile the graph using the selected provider.
        # The graph is created once and reused for subsequent questions.
        app = build_app(provider)

    # Catch common configuration and initialization errors.
    except (RuntimeError, ValueError, ImportError) as exc:

        # Display the error message using the standard error stream.
        print(f"\nConfiguration error:\n{exc}", file=sys.stderr)

        # Terminate the application with a non-zero exit code.
        sys.exit(1)

    # Display the welcome message and available commands.
    print(BANNER)

    # Display the active provider/model configuration.
    print(f"(using {config.describe()})\n")

    # Start an infinite loop to continuously receive user questions.
    while True:

        # Handle cases where the user interrupts the application.
        try:

            # Read the question entered by the user.
            # strip() removes unnecessary spaces around the input.
            question = input("You: ").strip()

        # Handle end-of-input or keyboard interruption.
        except (EOFError, KeyboardInterrupt):

            # Display a goodbye message.
            print("\nGoodbye!")

            # Stop the interactive loop.
            break

        # If the user enters nothing, skip this iteration.
        if not question:
            continue

        # Convert the command into lowercase.
        # This allows commands such as /EXIT and /Exit to work as well.
        cmd = question.lower()

        # Check whether the user wants to exit the application.
        if cmd in ("/exit", "/quit"):

            # Display a goodbye message.
            print("Goodbye!")

            # Exit the loop.
            break

        # Check whether the user wants to see the active model configuration.
        if cmd == "/model":

            # Display the provider and model configuration.
            print(f"  {config.describe()}")

            # Skip the remaining operations and wait for another input.
            continue

        # Check whether the user wants to view the graph structure.
        if cmd == "/graph":

            # Call the graph visualisation function.
            print_graph(app)

            # Return to the beginning of the loop.
            continue

        # Check whether the user wants to switch the model provider.
        if cmd == "/provider":

            # Handle errors that may occur while switching providers.
            try:

                # Display the provider selection menu again.
                provider = choose_provider()

                # Build a new graph using the newly selected provider.
                # The previous compiled graph is replaced by this graph.
                app = build_app(provider)

                # Display the updated configuration information.
                print(f"  Switched -> {config.describe()}")

            # Handle common errors during provider switching.
            except (RuntimeError, ValueError, ImportError) as exc:

                # Display the reason why the provider switch failed.
                print(f"  Switch failed: {exc}")

            # Return to the beginning of the chat loop.
            continue

        # Check whether the user wants to see the execution of each graph node.
        if cmd == "/steps":

            # Ask the user to enter the question that needs to be traced.
            raw = input("Question to trace: ").strip()

            # Continue only if the user entered a non-empty question.
            if raw:

                # Handle errors that may occur during graph execution.
                try:

                    # Execute the graph using stream().
                    # This displays the updates from each node as they execute.
                    run_with_trace(app, raw)

                # Catch any error that occurs during traced execution.
                except Exception as exc:

                    # Display the error type and error message.
                    print(f"  [error] {type(exc).__name__}: {exc}\n")

            # Return to the beginning of the chat loop.
            continue

        # ---- normal question: run the whole graph once -------------------

        # Execute the entire graph for a normal user question.
        try:

            # invoke() runs the graph from START to END.
            #
            # The initial input is a dictionary containing the user's question.
            # The graph passes the state through all three nodes.
            #
            # The final result is returned as a dictionary containing
            # the updated state, including final_output.
            final_state = app.invoke({"question": question})

        # Handle errors that occur during graph execution.
        except Exception as exc:

            # Display the error type and corresponding error message.
            print(f"FinDesk: [error] {type(exc).__name__}: {exc}\n")

            # Display a helpful connection or configuration troubleshooting hint.
            print(config.connection_hint() + "\n")

            # Skip the remaining statements and wait for another question.
            continue

        # The output_processing node has already created final_output.
        # Retrieve it from the final state and display it to the user.
        print(f"{final_state['final_output']}\n")


# Check whether this Python file is being executed directly.
# If it is imported into another Python file, main() will not execute.
if __name__ == "__main__":

    # Start the FinDesk V2 application.
    main()